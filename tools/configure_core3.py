#!/usr/bin/env python3
"""Configure a deliberately bounded Core3 instance from locally extracted media."""
from pathlib import Path
import json
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CORE = ROOT / 'vendor/Core3'
TRE = ROOT / 'runtime/assets/active_tre'

def main():
    config = CORE / 'MMOCoreORB/bin/conf/config.lua'
    if not config.exists() or not TRE.exists():
        raise SystemExit('Provision Core3 and extract the supplied media first.')
    upstream = config.read_text()
    tre_block = upstream.split('TreFiles = {', 1)[1].split('}', 1)[0]
    expected = re.findall(r'"([^\"]+\.tre)"', tre_block)
    available = {p.name for p in TRE.glob('*.tre')}
    selected = [name for name in expected if name in available]
    selected += sorted(available - set(selected), reverse=True)
    if not selected:
        raise SystemExit('No local TRE archives found.')
    prefix = '''-- SWGXR local viability profile; generated by tools/configure_core3.py.
-- Only supplied media archives are used; no replacement game assets are downloaded.
Core3.DBHost = "127.0.0.1"
Core3.DBName = "swgemu"
Core3.DBUser = "swgemu"
Core3.DBPass = "123456"
Core3.ZoneGalaxyID = 2
Core3.ZonesEnabled = {"tatooine"}
Core3.SpaceZonesEnabled = {}
Core3.TrePath = "/workspace/runtime/assets/active_tre"
Core3.TreFiles = {
'''
    suffix = '''}
Core3.MakePing = 0
Core3.MakeStatus = 0
Core3.MakeWeb = 0
Core3.ZoneProcessingThreads = 4
Core3.LoginAllowedConnections = 16
Core3.ZoneAllowedConnections = 32
Core3.MaxNavMeshJobs = 2
Core3.DumpObjFiles = 0
-- Startup association only; source shuttle landing/departure schedules are unchanged.
Core3.ShuttleZoneComponent = { BootDelay = 5000 }
Core3.AutoReg = 1
Core3.SWGXR = { RetailGroundOnly = true, StartAtStarport = true, SpawnX = 3599.894, SpawnY = -4780.4487, SpawnZ = 5.0 }
Core3.PlayerCreationManager = { EnableTutorial = false }
'''
    target = CORE / 'MMOCoreORB/bin/conf/config-local.lua'
    # Core3 may be starting while another build refreshes configuration.
    # Rename a complete sibling file so its Lua parser never sees a truncated file.
    with tempfile.NamedTemporaryFile(mode='w', dir=target.parent, prefix='.swgxr-config-', delete=False) as stream:
        stream.write(prefix + ''.join('    '+json.dumps(name)+',\n' for name in selected) + suffix)
        staged_config = Path(stream.name)
    staged_config.chmod(0o644)
    staged_config.replace(target)
    # Later patches can overlap earlier hunks, making reverse --check unreliable.
    # Reconstruct the pinned stack separately; overwrite only recognized states.
    patches = sorted((ROOT / 'server/patches').glob('*.patch'))
    paths = sorted({line[6:] for patch in patches for line in patch.read_text().splitlines()
                    if line.startswith('+++ b/')})
    with tempfile.TemporaryDirectory(prefix='swgxr-patches-') as temporary:
        tree = Path(temporary)
        subprocess.run(['git', 'init', '-q', str(tree)], check=True)
        known = {path: [] for path in paths}
        for path in paths:
            original = subprocess.run(['git', '-C', str(CORE), 'show', 'HEAD:'+path], capture_output=True)
            data = original.stdout if original.returncode == 0 else None
            known[path].append(data)
            if data is not None:
                target_file = tree/path
                target_file.parent.mkdir(parents=True, exist_ok=True)
                target_file.write_bytes(data)
        for patch in patches:
            subprocess.run(['git', '-C', str(tree), 'apply', str(patch)], check=True)
            for path in paths:
                known[path].append((tree/path).read_bytes() if (tree/path).exists() else None)
        for path in paths:
            current = (CORE/path).read_bytes() if (CORE/path).exists() else None
            if current not in known[path]:
                raise SystemExit('Preserving unrecognized Core3 changes: '+path)
        for path in paths:
            desired = (tree/path).read_bytes()
            if not (CORE/path).exists() or (CORE/path).read_bytes() != desired:
                (CORE/path).parent.mkdir(parents=True, exist_ok=True)
                (CORE/path).write_bytes(desired)
    subprocess.run([sys.executable, str(ROOT / 'tools/combat/install_crafting_profile.py')], check=True)
    report = {'profile': 'user_media_tatooine_only', 'archives': selected,
              'missing_from_standard_core3_profile': [x for x in expected if x not in available],
              'configuration': str(target.relative_to(ROOT)),
              'note': 'Missing standard archives are reported, not synthesized. Runtime validation required.'}
    out = ROOT / 'runtime/server/media-profile.json'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(report, indent=2)+'\n')
    print(f'Configured {len(selected)} archives; {len(report["missing_from_standard_core3_profile"])} standard archives absent.')

if __name__ == '__main__':
    main()

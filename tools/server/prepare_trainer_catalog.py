#!/usr/bin/env python3
"""Extract the six exact pinned Core3 trainer catalogues (no proprietary assets)."""
import hashlib,re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def main():
 source=ROOT/'vendor/Core3/MMOCoreORB/bin/scripts/screenplays/trainers/trainerData.lua'
 text=source.read_text();rows=[]
 for profession in ('artisan','brawler','entertainer','marksman','medic','scout'):
  block=re.search(r'\btrainer_'+profession+r'\s*=\s*\{([^}]+)\}',text).group(1)
  skills=re.findall(r'"([a-z0-9_]+)"',block)
  assert len(skills)==18
  rows.append('  {"trainer_'+profession+'", {'+', '.join('"'+s+'"'for s in skills)+'}},')
 out='// Generated by tools/server/prepare_trainer_catalog.py from pinned trainerData.lua\n// SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\n#ifndef SWGXR_TRAINER_CATALOG_H\n#define SWGXR_TRAINER_CATALOG_H\n#include <map>\n#include <vector>\n#include <string>\ninline const std::map<std::string,std::vector<std::string>>& swgxrTrainerCatalog(){\n static const std::map<std::string,std::vector<std::string>> catalog={\n'+'\n'.join(rows)+'\n };return catalog;\n}\n#endif\n'
 for target in (ROOT/'server/services/SwgxrTrainerCatalog.h',ROOT/'vendor/Core3/MMOCoreORB/src/server/zone/objects/creature/commands/SwgxrTrainerCatalog.h'):target.write_text(out)
 print('Extracted 108 original trainer skill IDs from',hashlib.sha256(source.read_bytes()).hexdigest())
if __name__=='__main__':main()
